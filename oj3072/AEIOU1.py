"""AEIOU"""
def main():
    """AEIOU"""
    aeiou = input().lower()
    if aeiou.count('a'):
        print(f"a : {aeiou.count('a')}")
    if aeiou.count('e'):
        print(f"e : {aeiou.count('e')}")
    if aeiou.count('i'):
        print(f"i : {aeiou.count('i')}")
    if aeiou.count('o'):
        print(f"o : {aeiou.count('o')}")
    if aeiou.count('u'):
        print(f"u : {aeiou.count('u')}")
main()
